/* Cau 23 */
SELECT DISTINCT DA.MADA
FROM DEAN AS DA
WHERE EXISTS (
    SELECT 1
    FROM PHANCONG AS PC
    INNER JOIN NHANVIEN AS NV
        ON NV.MANV = PC.MA_NVIEN
    WHERE PC.SODA = DA.MADA
      AND NV.HONV = N'Dinh'
)
OR EXISTS (
    SELECT 1
    FROM PHONGBAN AS PB
    INNER JOIN NHANVIEN AS TP
        ON TP.MANV = PB.TRPHG
    WHERE PB.MAPHG = DA.PHONG
      AND TP.HONV = N'Dinh'
);

/* Cau 24 */
SELECT NV.HONV, NV.TENLOT, NV.TENNV
FROM NHANVIEN AS NV
WHERE (
    SELECT COUNT(*)
    FROM THANNHAN AS TN
    WHERE TN.MA_NVIEN = NV.MANV
) > 2;

/* Cau 25 */
SELECT NV.HONV, NV.TENLOT, NV.TENNV
FROM NHANVIEN AS NV
WHERE NOT EXISTS (
    SELECT 1
    FROM THANNHAN AS TN
    WHERE TN.MA_NVIEN = NV.MANV
);

/* Cau 26 */
SELECT DISTINCT NV.HONV, NV.TENLOT, NV.TENNV
FROM NHANVIEN AS NV
WHERE EXISTS (
    SELECT 1
    FROM PHONGBAN AS PB
    WHERE PB.TRPHG = NV.MANV
)
AND EXISTS (
    SELECT 1
    FROM THANNHAN AS TN
    WHERE TN.MA_NVIEN = NV.MANV
);

/* Cau 27 */
SELECT DISTINCT NV.HONV, NV.TENLOT, NV.TENNV
FROM NHANVIEN AS NV
WHERE EXISTS (
    SELECT 1
    FROM PHONGBAN AS PB
    WHERE PB.TRPHG = NV.MANV
)
AND NOT EXISTS (
    SELECT 1
    FROM THANNHAN AS TN
    WHERE TN.MA_NVIEN = NV.MANV
);

/* Cau 28 */
SELECT NV.HONV, NV.TENLOT, NV.TENNV
FROM NHANVIEN AS NV
WHERE NV.LUONG > (
    SELECT AVG(NVNC.LUONG)
    FROM NHANVIEN AS NVNC
    INNER JOIN PHONGBAN AS PB
        ON PB.MAPHG = NVNC.PHG
    WHERE PB.TENPHG = N'Nghien cuu'
);

/* Cau 29 */
SELECT
    PB.TENPHG,
    TP.HONV,
    TP.TENLOT,
    TP.TENNV
FROM PHONGBAN AS PB
INNER JOIN NHANVIEN AS TP
    ON TP.MANV = PB.TRPHG
WHERE (
    SELECT COUNT(*)
    FROM NHANVIEN AS NV
    WHERE NV.PHG = PB.MAPHG
) >= ALL (
    SELECT (
        SELECT COUNT(*)
        FROM NHANVIEN AS NV2
        WHERE NV2.PHG = PB2.MAPHG
    )
    FROM PHONGBAN AS PB2
);

/* Cau 30 */
SELECT DISTINCT NV.HONV, NV.TENLOT, NV.TENNV, NV.DCHI
FROM NHANVIEN AS NV
WHERE EXISTS (
    SELECT 1
    FROM PHANCONG AS PC
    INNER JOIN DEAN AS DA
        ON DA.MADA = PC.SODA
    WHERE PC.MA_NVIEN = NV.MANV
      AND DA.DDIEM_DA = N'TP HCM'
)
AND NOT EXISTS (
    SELECT 1
    FROM DIADIEM_PHG AS DP
    WHERE DP.MAPHG = NV.PHG
      AND DP.DIADIEM = N'TP HCM'
);

/* Cau 31 */
SELECT DISTINCT NV.HONV, NV.TENLOT, NV.TENNV, NV.DCHI
FROM NHANVIEN AS NV
WHERE EXISTS (
    SELECT 1
    FROM PHANCONG AS PC
    INNER JOIN DEAN AS DA
        ON DA.MADA = PC.SODA
    WHERE PC.MA_NVIEN = NV.MANV
      AND DA.DDIEM_DA IS NOT NULL
      AND NOT EXISTS (
          SELECT 1
          FROM DIADIEM_PHG AS DP
          WHERE DP.MAPHG = NV.PHG
            AND DP.DIADIEM = DA.DDIEM_DA
      )
);
